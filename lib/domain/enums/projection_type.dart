/// Типы проекций чертежа / вида
enum ProjectionType {
  /// Фронтальная изометрическая (аксонометрическая) по ГОСТ 21.602 / СПДС
  /// Угол 45°, масштаб по оси X = 0.5, по осям Y и Z = 1:1
  gostFrontal45,

  /// Зеркальная фронтальная аксонометрия по ГОСТ (разворот осей,
  /// когда вертикальные стояки или стены заслоняют трассу сети)
  gostMirrored45,

  /// Прямоугольная изометрия (ISO 30° / 30°, масштаб 1:1:1)
  iso30,

  /// План сверху (2D вид X, Y)
  topPlan2d,

  /// Свободная 3D-орбита (интерактивное вращение двумя пальцами/мышью)
  orbit3d,
}
