/// Пресеты компоновки видового экрана на чертежном листе
enum ViewportLayoutPreset {
  /// По ширине листа над штампом (рекомендуемый СПДС/ГОСТ, макс. полезная ширина)
  wideAboveStamp,

  /// Во весь лист (AutoCAD Full Frame, штамп накладывается поверх модели с белой подложкой)
  fullSheet,

  /// Вертикальный столбец слева от штампа (для размещения справа ведомостей, спецификаций и примечаний)
  leftColumn,
}
